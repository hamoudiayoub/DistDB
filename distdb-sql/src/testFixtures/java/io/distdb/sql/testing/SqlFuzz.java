package io.distdb.sql.testing;

import io.distdb.env.RandomSource;
import io.distdb.env.SplittableRandomSource;
import java.util.ArrayList;
import java.util.List;

/**
 * Random queries for differential testing against PostgreSQL. From a seed it writes a sqllogictest
 * file (without results): two tables with NULLs, duplicates and indexes, then queries mixing
 * filters, joins, grouping, subqueries and set operations. PostgreSQL fills in the results ({@link
 * SqlLogic#complete}); DistDB must then give the same, on one node and on the cluster.
 *
 * <p>Values stay small, so PostgreSQL's 32-bit {@code INT} never overflows where DistDB's 64-bit
 * one would not; division is guarded with {@code NULLIF}, so no query fails.
 */
public final class SqlFuzz {

  private final RandomSource r;
  private final StringBuilder out = new StringBuilder();

  private SqlFuzz(long seed) {
    this.r = SplittableRandomSource.seeded(seed);
  }

  /** The file for {@code seed}, with {@code queries} queries. */
  public static String generate(long seed, int queries) {
    SqlFuzz f = new SqlFuzz(seed);
    f.schema();
    for (int i = 0; i < queries; i++) {
      f.query();
    }
    return f.out.toString();
  }

  // -----------------------------------------------------------------------------------------------
  // Schema and data

  /** A column: its name, its sqllogictest type letter, and whether it is text. */
  private record Column(String table, String name, char type, Kind kind) {
    String ref() {
      return table + "." + name;
    }
  }

  private enum Kind {
    INT,
    TEXT,
    NUMERIC
  }

  private static final List<Column> T1 =
      List.of(
          new Column("t1", "k", 'I', Kind.INT),
          new Column("t1", "a", 'I', Kind.INT),
          new Column("t1", "b", 'I', Kind.INT),
          new Column("t1", "s", 'T', Kind.TEXT),
          new Column("t1", "n", 'T', Kind.NUMERIC));
  private static final List<Column> T2 =
      List.of(
          new Column("t2", "k", 'I', Kind.INT),
          new Column("t2", "a", 'I', Kind.INT),
          new Column("t2", "c", 'I', Kind.INT),
          new Column("t2", "s", 'T', Kind.TEXT));
  private static final String[] WORDS = {"a", "b", "ab", "ba", "abc", "B", "", "a b", "zz"};

  private void schema() {
    out.append("# Generated by SqlFuzz: random queries, with the results PostgreSQL gave.\n\n");
    statement("CREATE TABLE t1 (k INT PRIMARY KEY, a INT, b INT, s TEXT, n NUMERIC(6, 2))");
    statement("CREATE TABLE t2 (k INT PRIMARY KEY, a INT, c INT, s TEXT)");
    statement("CREATE INDEX t1_a ON t1 (a)");
    statement("CREATE INDEX t2_c ON t2 (c, a)");
    statement("CREATE INDEX t1_s ON t1 (s)");
    StringBuilder rows = new StringBuilder();
    for (int k = 1; k <= 40; k++) {
      rows.append(k == 1 ? "" : ", ")
          .append("(")
          .append(k)
          .append(", ")
          .append(maybe(intVal(10)))
          .append(", ")
          .append(maybe(intVal(-5, 6)))
          .append(", ")
          .append(maybe(text()))
          .append(", ")
          .append(maybe(numeric()))
          .append(")");
    }
    statement("INSERT INTO t1 VALUES " + rows);
    rows.setLength(0);
    for (int k = 1; k <= 30; k++) {
      rows.append(k == 1 ? "" : ", ")
          .append("(")
          .append(k * 2)
          .append(", ")
          .append(maybe(intVal(10)))
          .append(", ")
          .append(maybe(intVal(-3, 8)))
          .append(", ")
          .append(maybe(text()))
          .append(")");
    }
    statement("INSERT INTO t2 VALUES " + rows);
  }

  private void statement(String sql) {
    out.append("statement ok\n").append(sql).append("\n\n");
  }

  private String maybe(String v) {
    return r.nextInt(8) == 0 ? "NULL" : v;
  }

  private String intVal(int bound) {
    return Integer.toString(r.nextInt(bound));
  }

  private String intVal(int from, int to) {
    return Integer.toString(r.nextInt(from, to));
  }

  private String text() {
    return "'" + WORDS[r.nextInt(WORDS.length)].replace("'", "''") + "'";
  }

  private String numeric() {
    int cents = r.nextInt(-999, 1000);
    return String.format(java.util.Locale.ROOT, "%.2f", cents / 100.0);
  }

  private <T> T pick(List<T> list) {
    return list.get(r.nextInt(list.size()));
  }

  // -----------------------------------------------------------------------------------------------
  // Expressions

  /** An expression and its type letter. */
  private record Expr(String sql, char type, Kind kind) {}

  private Expr expr(List<Column> cols, int depth) {
    Column c = pick(cols);
    if (depth <= 0 || r.nextInt(3) == 0) {
      return new Expr(c.ref(), c.type(), c.kind());
    }
    return switch (c.kind()) {
      case INT ->
          switch (r.nextInt(6)) {
            case 0 -> new Expr("(" + c.ref() + " + " + intVal(-3, 4) + ")", 'I', Kind.INT);
            case 1 -> {
              Column d = pickOf(cols, Kind.INT);
              yield new Expr("(" + c.ref() + " * " + d.ref() + ")", 'I', Kind.INT);
            }
            case 2 -> new Expr("abs(" + c.ref() + ")", 'I', Kind.INT);
            case 3 -> new Expr("coalesce(" + c.ref() + ", " + intVal(-9, 10) + ")", 'I', Kind.INT);
            case 4 ->
                new Expr(
                    "(" + c.ref() + " / NULLIF(" + pickOf(cols, Kind.INT).ref() + ", 0))",
                    'I',
                    Kind.INT);
            default ->
                new Expr(
                    "CASE WHEN "
                        + predicate(cols, 0)
                        + " THEN "
                        + c.ref()
                        + " ELSE "
                        + intVal(-9, 10)
                        + " END",
                    'I',
                    Kind.INT);
          };
      case TEXT ->
          switch (r.nextInt(4)) {
            case 0 -> new Expr("upper(" + c.ref() + ")", 'T', Kind.TEXT);
            case 1 -> new Expr("(" + c.ref() + " || 'x')", 'T', Kind.TEXT);
            case 2 -> new Expr("coalesce(" + c.ref() + ", 'none')", 'T', Kind.TEXT);
            default -> new Expr("substr(" + c.ref() + ", 2)", 'T', Kind.TEXT);
          };
      case NUMERIC ->
          switch (r.nextInt(3)) {
            case 0 -> new Expr("(" + c.ref() + " * 2)", 'T', Kind.NUMERIC);
            case 1 -> new Expr("round(" + c.ref() + ", 1)", 'T', Kind.NUMERIC);
            default -> new Expr("(" + c.ref() + " + 0.5)", 'T', Kind.NUMERIC);
          };
    };
  }

  private Column pickOf(List<Column> cols, Kind kind) {
    List<Column> of = cols.stream().filter(c -> c.kind() == kind).toList();
    return of.isEmpty() ? pick(cols) : pick(of);
  }

  private String literal(Kind kind) {
    return switch (kind) {
      case INT -> intVal(-3, 10);
      case TEXT -> text();
      case NUMERIC -> numeric();
    };
  }

  private String predicate(List<Column> cols, int depth) {
    if (depth > 0 && r.nextInt(3) == 0) {
      String op = r.nextBoolean() ? " AND " : " OR ";
      return "(" + predicate(cols, depth - 1) + op + predicate(cols, depth - 1) + ")";
    }
    if (depth > 0 && r.nextInt(8) == 0) {
      return "NOT " + predicate(cols, depth - 1);
    }
    Column c = pick(cols);
    String[] cmp = {"=", "<>", "<", "<=", ">", ">="};
    return switch (r.nextInt(7)) {
      case 0 -> c.ref() + (r.nextBoolean() ? " IS NULL" : " IS NOT NULL");
      case 1 -> c.ref() + " BETWEEN " + literal(c.kind()) + " AND " + literal(c.kind());
      case 2 -> {
        StringBuilder in = new StringBuilder(c.ref() + (r.nextBoolean() ? " IN (" : " NOT IN ("));
        int n = r.nextInt(1, 4);
        for (int i = 0; i < n; i++) {
          in.append(i == 0 ? "" : ", ").append(r.nextInt(6) == 0 ? "NULL" : literal(c.kind()));
        }
        yield in.append(")").toString();
      }
      case 3 -> {
        if (c.kind() == Kind.TEXT) {
          String[] patterns = {"'a%'", "'%b'", "'_b%'", "'%'", "'a_'", "'%a%'"};
          yield c.ref() + (r.nextBoolean() ? " LIKE " : " NOT LIKE ") + patterns[r.nextInt(6)];
        }
        yield c.ref() + " " + cmp[r.nextInt(6)] + " " + literal(c.kind());
      }
      case 4 -> {
        Column d = pickOf(cols, c.kind());
        yield c.ref() + " " + cmp[r.nextInt(6)] + " " + d.ref();
      }
      default -> c.ref() + " " + cmp[r.nextInt(6)] + " " + literal(c.kind());
    };
  }

  // -----------------------------------------------------------------------------------------------
  // Queries

  private void query() {
    switch (r.nextInt(8)) {
      case 0, 1 -> select();
      case 2 -> join();
      case 3, 4 -> aggregate();
      case 5 -> subquery();
      case 6 -> setOp();
      default -> distinct();
    }
  }

  private void emit(String types, String sort, String sql) {
    out.append("query ")
        .append(types)
        .append(' ')
        .append(sort)
        .append('\n')
        .append(sql)
        .append("\n----\n\n");
  }

  private void select() {
    List<Column> cols = r.nextBoolean() ? T1 : T2;
    String t = cols.get(0).table();
    List<Expr> items = new ArrayList<>();
    int n = r.nextInt(1, 4);
    for (int i = 0; i < n; i++) {
      items.add(expr(cols, 2));
    }
    StringBuilder sql = new StringBuilder("SELECT ");
    StringBuilder types = new StringBuilder();
    for (int i = 0; i < items.size(); i++) {
      sql.append(i == 0 ? "" : ", ").append(items.get(i).sql());
      types.append(items.get(i).type());
    }
    sql.append(" FROM ").append(t);
    if (r.nextInt(5) != 0) {
      sql.append(" WHERE ").append(predicate(cols, 2));
    }
    if (r.nextInt(3) == 0) {
      // A LIMIT needs a total order: every output column, then the key.
      sql.append(" ORDER BY ");
      for (int i = 1; i <= items.size(); i++) {
        sql.append(i).append(r.nextBoolean() ? " DESC" : "").append(", ");
      }
      sql.append(t).append(".k LIMIT ").append(r.nextInt(1, 8));
      emit(types.toString(), "nosort", sql.toString());
    } else {
      emit(types.toString(), "rowsort", sql.toString());
    }
  }

  private void join() {
    List<Column> both = new ArrayList<>(T1);
    both.addAll(T2);
    String kind = pick(List.of("JOIN", "LEFT JOIN", "RIGHT JOIN", "FULL JOIN", "JOIN"));
    String on =
        switch (r.nextInt(4)) {
          case 0 -> "t1.a = t2.a";
          case 1 -> "t1.k = t2.k";
          case 2 -> "t1.b = t2.c";
          default -> "t1.a = t2.c AND " + predicate(both, 0);
        };
    Expr x = expr(T1, 1);
    Expr y = expr(T2, 1);
    String sql = "SELECT " + x.sql() + ", " + y.sql() + " FROM t1 " + kind + " t2 ON " + on;
    if (r.nextBoolean()) {
      sql += " WHERE " + predicate(both, 1);
    }
    emit("" + x.type() + y.type(), "rowsort", sql);
  }

  private void aggregate() {
    List<Column> cols = r.nextBoolean() ? T1 : T2;
    String t = cols.get(0).table();
    Column g = pick(cols.subList(1, cols.size()));
    List<String> aggs = new ArrayList<>();
    StringBuilder types = new StringBuilder(r.nextInt(4) == 0 ? "" : String.valueOf(g.type()));
    boolean grouped = !types.isEmpty();
    int n = r.nextInt(1, 4);
    for (int i = 0; i < n; i++) {
      Column c = pick(cols);
      switch (r.nextInt(6)) {
        case 0 -> {
          aggs.add("count(*)");
          types.append('I');
        }
        case 1 -> {
          aggs.add("count(" + (r.nextBoolean() ? "DISTINCT " : "") + c.ref() + ")");
          types.append('I');
        }
        case 2 -> {
          Column num = pickNumeric(cols);
          aggs.add("sum(" + num.ref() + ")");
          types.append(num.kind() == Kind.NUMERIC ? 'T' : 'I');
        }
        case 3 -> {
          aggs.add("avg(" + pickNumeric(cols).ref() + ")");
          types.append('T');
        }
        default -> {
          aggs.add((r.nextBoolean() ? "min(" : "max(") + c.ref() + ")");
          types.append(c.type());
        }
      }
    }
    StringBuilder sql = new StringBuilder("SELECT ");
    if (grouped) {
      sql.append(g.ref()).append(", ");
    }
    sql.append(String.join(", ", aggs)).append(" FROM ").append(t);
    if (r.nextBoolean()) {
      sql.append(" WHERE ").append(predicate(cols, 1));
    }
    if (grouped) {
      sql.append(" GROUP BY ").append(g.ref());
      if (r.nextInt(3) == 0) {
        sql.append(" HAVING count(*) > ").append(r.nextInt(0, 3));
      }
    }
    emit(types.toString(), "rowsort", sql.toString());
  }

  private Column pickNumeric(List<Column> cols) {
    List<Column> of = cols.stream().filter(c -> c.kind() != Kind.TEXT).toList();
    return pick(of);
  }

  private void subquery() {
    String sql =
        switch (r.nextInt(4)) {
          case 0 ->
              "SELECT t1.k FROM t1 WHERE t1.a "
                  + (r.nextBoolean() ? "IN" : "NOT IN")
                  + " (SELECT t2.a FROM t2 WHERE "
                  + predicate(T2, 1)
                  + ")";
          case 1 ->
              "SELECT t1.k FROM t1 WHERE "
                  + (r.nextBoolean() ? "" : "NOT ")
                  + "EXISTS (SELECT 1 FROM t2 WHERE t2.a = t1.a AND "
                  + predicate(T2, 0)
                  + ")";
          case 2 ->
              "SELECT t1.k, (SELECT count(*) FROM t2 WHERE t2.c = t1.b) FROM t1 WHERE "
                  + predicate(T1, 1);
          default ->
              "SELECT t2.k FROM t2 WHERE t2.c > (SELECT avg(t1.b) FROM t1 WHERE t1.a = t2.a)";
        };
    emit(sql.contains("count(*)") ? "II" : "I", "rowsort", sql);
  }

  private void setOp() {
    String op =
        pick(List.of("UNION", "UNION ALL", "INTERSECT", "EXCEPT", "INTERSECT ALL", "EXCEPT ALL"));
    String sql =
        "SELECT t1.a FROM t1 WHERE "
            + predicate(T1, 1)
            + " "
            + op
            + " SELECT t2.a FROM t2 WHERE "
            + predicate(T2, 1);
    emit("I", "rowsort", sql);
  }

  private void distinct() {
    List<Column> cols = r.nextBoolean() ? T1 : T2;
    Expr e = expr(cols, 1);
    emit(
        String.valueOf(e.type()),
        "rowsort",
        "SELECT DISTINCT "
            + e.sql()
            + " FROM "
            + cols.get(0).table()
            + " WHERE "
            + predicate(cols, 1));
  }
}
